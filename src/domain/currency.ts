export function isSupportedCurrency(code: string | null | undefined): code is string {
  return typeof code === 'string' && currencies.some((currency) => currency.code === code);
}

/** Maps a locale such as "en-CM" or "fr_FR" to its region's currency, or null if unknown. */
export function currencyForLocale(locale: string | null | undefined): string | null {
  const region = /[-_]([A-Za-z]{2})(?:[-_]|$)/.exec(locale ?? '')?.[1]?.toUpperCase();
  return region ? (regionCurrency[region] ?? null) : null;
}

export function detectCurrencyCode(): string {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale;
    return currencyForLocale(locale) ?? defaultCurrencyCode;
  } catch {
    return defaultCurrencyCode;
  }
}

export function searchCurrencies(query: string): readonly Currency[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return currencies;
  return currencies.filter(
    (currency) =>
      currency.code.toLowerCase().includes(needle) || currency.name.toLowerCase().includes(needle),
  );
}

let activeCurrency = defaultCurrencyCode;

export function getCurrencyCode(): string {
  return activeCurrency;
}

export function setActiveCurrency(code: string): void {
  if (isSupportedCurrency(code)) activeCurrency = code;
}

export function formatMoney(amount: number): string {
  const safe = Number.isFinite(amount) ? Math.trunc(amount) : 0;
  return `${safe.toLocaleString('en-US')} ${activeCurrency}`;
}
